async function seed() {
  const conn = await mysql.createConnection(process.env.DATABASE_URL);
  
  console.log('Starting SEO taxonomy seeding...');
  
  // Clear existing data
  console.log('Clearing existing keywords and updating tags...');
  await conn.execute('DELETE FROM keywords');
  
  // Seed Primary Keywords (1000)
  console.log('Seeding primary keywords...');
  let primaryCount = 0;
  for (const kw of PRIMARY_KEYWORDS) {
    const slug = kw.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
    try {
      await conn.execute(
        'INSERT INTO keywords (name, slug, keywordType, category, isActive) VALUES (?, ?, ?, ?, true)',
        [kw.name, slug, 'primary', kw.category]
      );
      primaryCount++;
    } catch (e) {
      if (e.code !== 'ER_DUP_ENTRY') console.error('Error inserting primary keyword:', kw.name, e.message);
    }
  }
  console.log(`Inserted ${primaryCount} primary keywords`);
  
  // Seed Secondary Keywords (2000)
  console.log('Seeding secondary keywords...');
  let secondaryCount = 0;
  for (const kw of SECONDARY_KEYWORDS) {
    const slug = kw.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
    try {
      await conn.execute(
        'INSERT INTO keywords (name, slug, keywordType, category, isActive) VALUES (?, ?, ?, ?, true)',
        [kw.name, slug, 'secondary', kw.category]
      );
      secondaryCount++;
    } catch (e) {
      if (e.code !== 'ER_DUP_ENTRY') console.error('Error inserting secondary keyword:', kw.name, e.message);
    }
  }
  console.log(`Inserted ${secondaryCount} secondary keywords`);
  
  // Seed Tags (500)
  console.log('Seeding tags...');
  let tagCount = 0;
  for (const tag of TAGS) {
    const slug = tag.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
    try {
      await conn.execute(
        'INSERT INTO tags (name, slug, tagType, isActive) VALUES (?, ?, ?, true) ON DUPLICATE KEY UPDATE tagType = VALUES(tagType), isActive = true',
        [tag.name, slug, tag.tagType]
      );
      tagCount++;
    } catch (e) {
      console.error('Error inserting tag:', tag.name, e.message);
    }
  }
  console.log(`Inserted/updated ${tagCount} tags`);
  
  // Summary
  const [keywordStats] = await conn.execute(
    'SELECT keywordType, COUNT(*) as count FROM keywords GROUP BY keywordType'
  );
  const [tagStats] = await conn.execute(
    'SELECT tagType, COUNT(*) as count FROM tags WHERE isActive = true GROUP BY tagType'
  );
  
  console.log('\n=== SEEDING COMPLETE ===');
  console.log('Keywords:', keywordStats);
  console.log('Tags:', tagStats);
  
  await conn.end();
}

seed().catch(console.error);
